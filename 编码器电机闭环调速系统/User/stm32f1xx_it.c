/**
  * @brief  此功能负责处理系统定时器处理程序
  * @param  无
  * @retval 无
  */
void SysTick_Handler(void)
{
  /* USER CODE BEGIN SysTick_IRQn 0 */
  TB6612_SetState();//设置电机状态
  TB6612_SetSpeed();//设置电机速度
  /* USER CODE END SysTick_IRQn 0 */
  HAL_IncTick();
  /* USER CODE BEGIN SysTick_IRQn 1 */

  /* USER CODE END SysTick_IRQn 1 */
}

/**
  * @brief 此功能负责处理外部中断线路0的中断事件
  */
void EXTI0_IRQHandler(void)
{
  __HAL_GPIO_EXTI_CLEAR_IT(KEY2_reverse_Pin);//强制清除 EXTI13 的挂起标志位
  HAL_GPIO_EXTI_IRQHandler(KEY1_switch_Pin);//处理 EXTI0
}

/**
  * @brief 此功能负责处理 EXTI 线路[15:10]的中断信号
  */
void EXTI15_10_IRQHandler(void)
{
  HAL_GPIO_EXTI_IRQHandler(KEY2_reverse_Pin);//处理 EXTI13
}



